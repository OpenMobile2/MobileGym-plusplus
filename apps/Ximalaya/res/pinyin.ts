/**
 * 获取中文文本的拼音首字母
 * 例: pinyinInitials('小说') → 'xs'
 *     pinyinInitials('玄幻修仙') → 'hx xx' → 'hxxx' (无空格)
 * 非中文字符保留原样(小写)
 */
export function pinyinInitials(text: string): string {
  let result = '';
  for (const char of text) {
    let found = false;
    for (const [initial, chars] of Object.entries(MAP)) {
      if (chars.includes(char)) {
        result += initial;
        found = true;
        break;
      }
    }
    if (!found) result += char.toLowerCase();
  }
  return result;
}

/**
 * 获取文本的完整搜索索引(中文原文 + 拼音首字母)
 * 例: '小说' → '小说 xs'
 */
export function searchIndex(text: string): string {
  return (text + ' ' + pinyinInitials(text)).toLowerCase();
}
