def svg_cover(title: str, idx: int) -> str:
    color = PALETTE[idx % len(PALETTE)]
    short = title[:4]
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 160">'
        f'<rect width="120" height="160" fill="{color}"/>'
        f'<rect x="8" y="8" width="104" height="144" fill="none" stroke="#ffffff55" stroke-width="1"/>'
        f'<text x="60" y="76" font-size="22" fill="#fff" text-anchor="middle" font-family="serif">{short[:2]}</text>'
        f'<text x="60" y="104" font-size="22" fill="#fff" text-anchor="middle" font-family="serif">{short[2:4]}</text>'
        f"</svg>"
    )
    return "data:image/svg+xml;utf8," + urllib.parse.quote(svg)


def svg_avatar(name: str, idx: int) -> str:
    color = PALETTE[(idx + 3) % len(PALETTE)]
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">'
        f'<circle cx="32" cy="32" r="32" fill="{color}"/>'
        f'<text x="32" y="41" font-size="26" fill="#fff" text-anchor="middle" font-family="sans-serif">{name[0]}</text>'
        f"</svg>"
    )
    return "data:image/svg+xml;utf8," + urllib.parse.quote(svg)


def cover_path(book_id: str, title: str, idx: int) -> str:
    p = COVER_DIR / f"{book_id}.png"
    if p.exists() and p.stat().st_size > 10_000:
        return f"/@app-assets/FanqieXiaoshuo/covers/{book_id}.png"
    return svg_cover(title, idx)


def avatar_path(aid: str, name: str, idx: int) -> str:
    p = AVATAR_DIR / f"{aid}.png"
    if p.exists() and p.stat().st_size > 10_000:
        return f"/@app-assets/FanqieXiaoshuo/avatars/{aid}.png"
    return svg_avatar(name, idx)


