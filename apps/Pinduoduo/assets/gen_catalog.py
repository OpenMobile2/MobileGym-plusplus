def price_triple(lo, hi):
    pin = round(random.uniform(lo, hi), 2)
    # 拼单价常带小数尾巴(如 .91 .89),补贴风
    if random.random() < 0.5:
        pin = round(pin - random.choice([0.03, 0.07, 0.09, 0.11]), 2)
    if pin < 1:
        pin = round(random.uniform(lo, hi), 1)
    single = round(pin * random.uniform(1.08, 1.25), 2)
    origin = round(single * random.uniform(1.4, 2.6), 2)
    return pin, single, origin


def sold_str():
    r = random.random()
    if r < 0.25:
        return f"已拼{random.randint(1, 9)}.{random.randint(1,9)}万件"
    if r < 0.55:
        return f"已拼{random.randint(1, 60)}万件"
    if r < 0.8:
        return f"已拼{random.randint(200, 9900)}件"
    return f"已拼{random.randint(10, 199)}件"


def gen_shops():
    shops = []
    idx = 0
    # 92 新店铺,尽量覆盖各品类
    while len(shops) < 92:
        cat = CATEGORY_NAMES[idx % len(CATEGORY_NAMES)]
        pre = random.choice(SHOP_PREFIX)
        suf = random.choice(SHOP_SUFFIX[cat])
        name = pre + suf
        sid = f"s_g{len(shops):03d}"
        badge = random.choices(BADGES, weights=[3, 2, 3])[0]
        gts = random.sample(GUARANTEES_POOL, k=random.randint(2, 3))
        sold = random.choice([
            f"近期本店已拼{random.randint(1, 30)}万件",
            f"近期本店已拼{random.randint(2000, 9000)}件",
            f"店铺评分 4.{random.randint(6, 9)}",
        ])
        shops.append({
            "id": sid, "name": name,
            "logo": f"{AVATAR_IMG}/{sid}.png",
            "badge": badge, "soldTip": sold, "guarantees": gts,
            "_cat": cat,
        })
        idx += 1
    return shops


def gen_items(shops):
    items = []
    prompts = {}
    reviews = []
    # 每类目标数量:均分 980
    per_cat = 980 // len(CATEGORY_NAMES)
    remainder = 980 - per_cat * len(CATEGORY_NAMES)
    shops_by_cat = {}
    for sh in shops:
        shops_by_cat.setdefault(sh["_cat"], []).append(sh)
    # 也允许挂到 curated 店铺
    all_shop_ids = [s["id"] for s in shops] + CURATED_SHOPS

    n = 0
    for ci, cat in enumerate(CATEGORY_NAMES):
        target = per_cat + (1 if ci < remainder else 0)
        cfg = CATEGORIES[cat]
        concepts = cfg["concepts"]
        for k in range(target):
            n += 1
            iid = f"g{n:04d}"
            base_title, subj, (lo, hi), specs = concepts[k % len(concepts)]
            # 加区分修饰,保证标题与生图主体唯一
            color_hint = random.choice(COLORS)
            variant = random.choice(["新款", "2026款", "加厚款", "升级款", "旗舰款", "轻奢款", "基础款", "限量款", "爆款", "百亿补贴款"])
            brandword = random.choice(SHOP_PREFIX)
            title = f"{brandword} {base_title} {variant}"
            # 生图主体:主体描述 + 颜色/变体,浅背景电商风(gen_item_images 会补 STYLE)
            prompt_subject = f"{subj},{color_hint}调,{variant}"
            pin, single, origin = price_triple(lo, hi)
            # 挂店铺:优先同品类店铺,否则任意
            pool = shops_by_cat.get(cat, []) or shops
            shop = random.choice(pool) if random.random() < 0.7 else None
            shop_id = shop["id"] if shop else random.choice(all_shop_ids)
            subsidy = random.random() < 0.28
            fufei = random.random() < 0.8
            tags = random.sample(cfg["tags"], k=random.randint(1, 2))
            if subsidy and "百亿补贴" not in tags:
                tags = ["百亿补贴"] + tags[:1]
            rc = random.choice([random.randint(50, 999), random.randint(1000, 99999), random.randint(100000, 900000)])
            item = {
                "id": iid, "shopId": shop_id, "title": title,
                "image": f"{ITEM_IMG}/{iid}.png",
                "gallery": [f"{ITEM_IMG}/{iid}.png", f"{ITEM_IMG}/{iid}_2.png"],
                "detailImages": [f"{ITEM_IMG}/{iid}_d.png"],
                "pinPrice": pin, "singlePrice": single, "originPrice": origin,
                "sold": sold_str(),
                "tags": tags,
                "specs": [{"name": nm, "options": list(op)} for nm, op in specs],
                "reviewCount": rc,
                "reviewTags": random.sample(["质量不错", "物流快", "很实惠", "做工好", "回购", "包装好", "性价比高", "正品"], k=3),
                "freeShipping": True,
                "fufei": fufei,
                "subsidy": subsidy,
                "category": cat,
            }
            items.append(item)
            prompts[iid] = prompt_subject
            # 约 30% 商品挂 1-2 条评价种子
            if random.random() < 0.3:
                for _ in range(random.randint(1, 2)):
                    pos = random.random() < 0.85
                    reviews.append({
                        "id": f"rv_{iid}_{len(reviews)}",
                        "itemId": iid,
                        "user": random.choice(REVIEW_USERS),
                        "avatar": "/@app-assets/Pinduoduo/avatars/u_me.svg",
                        "rating": 5 if pos and random.random() < 0.7 else (4 if pos else 3),
                        "content": random.choice(REVIEW_TEXT_POS if pos else REVIEW_TEXT_MID),
                        "images": [f"{ITEM_IMG}/{iid}_2.png"] if random.random() < 0.35 else [],
                        "tags": random.sample(item["reviewTags"], k=random.randint(1, 2)),
                    })
    return items, prompts, reviews


def main():
    shops = gen_shops()
    items, prompts, reviews = gen_items(shops)
    # 落 App 数据时去掉店铺的内部 _cat 字段
    shops_out = [{k: v for k, v in s.items() if k != "_cat"} for s in shops]

    catalog = {"shops": shops_out, "items": items, "reviews": reviews}
    (DATA_DIR / "catalog.json").write_text(
        json.dumps(catalog, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    # 生图 prompt(含店铺 logo 提示)
    for s in shops:
        prompts[f"__shop__{s['id']}"] = f"{s['name']}的品牌标识logo,简约扁平电商店铺图标,{s['_cat']}类目,纯色背景,圆形构图"
    (HERE / "prompts.json").write_text(
        json.dumps(prompts, ensure_ascii=False, indent=0), encoding="utf-8")

    print(f"shops={len(shops_out)} items={len(items)} reviews={len(reviews)} prompts={len(prompts)}")
    # 简单自检
    ids = [i["id"] for i in items]
    assert len(ids) == len(set(ids)), "商品 id 重复"
    print("catalog.json + prompts.json 写出完成")


if __name__ == "__main__":
    main()
